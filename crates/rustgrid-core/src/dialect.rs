#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn each_dialect_offers_its_own_builtin_functions() {
        assert!(
            DriverDialect::Mysql
                .builtin_functions()
                .contains(&"JSON_EXTRACT")
        );
        assert!(
            DriverDialect::SqlServer
                .builtin_functions()
                .contains(&"GETDATE")
        );
        assert!(
            DriverDialect::Sqlite
                .builtin_functions()
                .contains(&"STRFTIME")
        );
        assert!(DriverDialect::Postgres.builtin_functions().contains(&"NOW"));
        assert!(
            DriverDialect::Oracle
                .builtin_functions()
                .contains(&"SYSDATE")
        );
        assert!(DriverDialect::Generic.builtin_functions().is_empty());
    }
}
