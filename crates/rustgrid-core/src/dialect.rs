//! SQL dialect data shared by the UI and drivers.
//!
//! [`DriverDialect`] carries the engine-specific SQL data the app needs (today the built-in
//! function list offered by completion) without the app matching on the engine id.

/// The SQL dialect family a driver speaks.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Hash)]
pub enum DriverDialect {
    /// MySQL / MariaDB.
    Mysql,
    /// Microsoft SQL Server (T-SQL).
    SqlServer,
    /// SQLite.
    Sqlite,
    /// PostgreSQL.
    Postgres,
    /// Oracle Database.
    Oracle,
    /// A dialect we have no specific data for yet.
    #[default]
    Generic,
}

impl DriverDialect {
    /// The characters this dialect wraps an identifier in: `` ` `` for MySQL/SQLite, `[`/`]` for
    /// SQL Server, `"` for PostgreSQL/Oracle and the generic dialect.
    pub fn identifier_quote(self) -> (char, char) {
        match self {
            DriverDialect::Mysql | DriverDialect::Sqlite => ('`', '`'),
            DriverDialect::SqlServer => ('[', ']'),
            DriverDialect::Postgres | DriverDialect::Oracle | DriverDialect::Generic => ('"', '"'),
        }
    }

    /// Quote `name` as an identifier in this dialect, doubling any embedded closing quote. Used by
    /// the SQL-dump writer to build portable `INSERT` column/table names.
    pub fn quote_identifier(self, name: &str) -> String {
        let (open, close) = self.identifier_quote();
        let mut quoted = String::with_capacity(name.len() + 2);
        quoted.push(open);
        for ch in name.chars() {
            if ch == close {
                quoted.push(close);
            }
            quoted.push(ch);
        }
        quoted.push(close);
        quoted
    }

    /// Quote a possibly schema-qualified table name, one identifier at a time, so
    /// `public.users` becomes `"public"."users"` rather than a single quoted name containing a
    /// dot. Used by previews that render table names outside a driver.
    pub fn quote_table_name(self, name: &str) -> String {
        name.split('.')
            .map(|part| self.quote_identifier(part))
            .collect::<Vec<_>>()
            .join(".")
    }

    /// Whether `LIMIT`/`OFFSET` + `FETCH` pagination needs an `ORDER BY`: SQL Server and Oracle
    /// reject `OFFSET … FETCH NEXT` without one, while MySQL/SQLite/PostgreSQL page without it.
    pub fn paging_needs_order(self) -> bool {
        matches!(self, DriverDialect::SqlServer | DriverDialect::Oracle)
    }

    /// The paging clause a page of `limit` rows starting at `offset` uses, in this dialect's own
    /// syntax. Used by the grid's status line, so it matches the statement the driver ran.
    pub fn paging_clause(self, offset: u64, limit: u64) -> String {
        match self {
            DriverDialect::Mysql => format!("LIMIT {offset},{limit}"),
            DriverDialect::SqlServer | DriverDialect::Oracle => {
                format!("OFFSET {offset} ROWS FETCH NEXT {limit} ROWS ONLY")
            }
            DriverDialect::Sqlite | DriverDialect::Postgres | DriverDialect::Generic => {
                format!("LIMIT {limit} OFFSET {offset}")
            }
        }
    }

    /// The built-in function names completion offers for this dialect. Kept static so the editor
    /// can offer them without a database round-trip; engines without a curated list contribute
    /// theirs as they are added (their stored functions are still offered).
    pub fn builtin_functions(self) -> &'static [&'static str] {
        match self {
            DriverDialect::Mysql => MYSQL_FUNCTIONS,
            DriverDialect::SqlServer => SQLSERVER_FUNCTIONS,
            DriverDialect::Sqlite => SQLITE_FUNCTIONS,
            DriverDialect::Postgres => POSTGRES_FUNCTIONS,
            DriverDialect::Oracle => ORACLE_FUNCTIONS,
            DriverDialect::Generic => &[],
        }
    }
}

