//! SQL dialect data shared by the UI and drivers.
//!
//! [`DriverDialect`] carries the engine-specific SQL data the app needs (today the built-in
//! function list offered by completion) without the app matching on the engine id.

/// The SQL dialect family a driver speaks.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Hash)]
pub enum DriverDialect {
    /// MySQL / MariaDB.
    Mysql,
    /// Microsoft SQL Server (T-SQL).
    SqlServer,
    /// SQLite.
    Sqlite,
    /// A dialect we have no specific data for yet.
    #[default]
    Generic,
}

impl DriverDialect {
    /// The built-in function names completion offers for this dialect. Kept static so the editor
    /// can offer them without a database round-trip; engines without a curated list contribute
    /// theirs as they are added (their stored functions are still offered).
    pub fn builtin_functions(self) -> &'static [&'static str] {
        match self {
            DriverDialect::Mysql => MYSQL_FUNCTIONS,
            DriverDialect::SqlServer | DriverDialect::Sqlite | DriverDialect::Generic => &[],
        }
    }
}

