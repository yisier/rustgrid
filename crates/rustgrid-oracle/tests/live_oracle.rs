//! Live Oracle integration test, ignored by default.
//!
//! Enable with the `RUSTGRID_ORACLE_*` environment variables and:
//!
//! ```text
//! cargo test -p rustgrid-oracle -- --ignored
//! ```
//!
//! Defaults: host `localhost`, port `1521`, user `system`, service `FREEPDB1`
//! (`docker run -d --name rg-oracle -p 1521:1521 -e ORACLE_PASSWORD=oracle gvenzl/oracle-free:23-slim`).

use std::collections::BTreeMap;

use rustgrid_core::{
    ConnectionConfig, ConnectionOptions, Driver, DriverDialect, DriverId, RowInsert, RowUpdate,
};
use rustgrid_oracle::OracleDriver;

fn env(key: &str, default: &str) -> String {
    std::env::var(key).unwrap_or_else(|_| default.to_string())
}

fn config() -> ConnectionConfig {
    ConnectionConfig {
        driver: DriverId::new("oracle"),
        host: env("RUSTGRID_ORACLE_HOST", "localhost"),
        port: env("RUSTGRID_ORACLE_PORT", "1521").parse().unwrap_or(1521),
        username: env("RUSTGRID_ORACLE_USER", "system"),
        password: std::env::var("RUSTGRID_ORACLE_PASSWORD").ok(),
        database: Some(env("RUSTGRID_ORACLE_SERVICE", "FREEPDB1")),
        options: BTreeMap::new(),
        settings: ConnectionOptions::default(),
    }
}

#[test]
fn driver_metadata() {
    let driver = OracleDriver::new();
    assert_eq!(driver.id(), DriverId::new("oracle"));
    assert_eq!(driver.default_port(), 1521);
    assert_eq!(driver.dialect(), DriverDialect::Oracle);
    assert!(driver.supports_schemas());
    assert!(driver.supports_users());
    assert!(!driver.supports_database_management());
}

#[test]
#[ignore = "requires a live Oracle server (RUSTGRID_ORACLE_PASSWORD)"]
fn connects_and_browses() {
    let runtime = tokio::runtime::Runtime::new().unwrap();
    runtime.block_on(async {
        let driver = OracleDriver::new();
        let connection = driver.connect(&config()).await.expect("connect");

        let databases = connection.list_databases().await.expect("databases");
        assert!(!databases.is_empty());

        let schemas = connection.list_schemas("").await.expect("schemas");
        assert!(!schemas.iter().any(|schema| schema == "SYS"));

        let version = connection.server_version().await.expect("version");
        assert!(!version.is_empty());

        // Arbitrary SQL, including a statement that ends with a semicolon and a PL/SQL block.
        connection
            .execute_query(None, "SELECT 1 FROM dual;")
            .await
            .expect("trailing semicolon is accepted");

        let results = connection
            .execute_query_many(None, "BEGIN NULL; END;")
            .await
            .expect("PL/SQL block runs");
        assert!(results.is_empty() || results.iter().all(|result| !result.has_result_set));

        connection.close().await.expect("close");
    });
}

#[test]
#[ignore = "requires a live Oracle server (RUSTGRID_ORACLE_PASSWORD)"]
fn edits_a_table() {
    let runtime = tokio::runtime::Runtime::new().unwrap();
    runtime.block_on(async {
        let driver = OracleDriver::new();
        let connection = driver.connect(&config()).await.expect("connect");

        connection
            .execute_query(None, "DROP TABLE \"APP\".\"RG_T\"")
            .await
            .ok();
        connection
            .execute_query(
                None,
                "CREATE TABLE \"APP\".\"RG_T\" (\
                   \"ID\" NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \
                   \"NAME\" VARCHAR2(50), \"CREATED\" DATE, \
                   \"NAME_LEN\" NUMBER GENERATED ALWAYS AS (LENGTH(\"NAME\")) VIRTUAL)",
            )
            .await
            .expect("create table");

        let page = connection
            .fetch_page("", "APP.RG_T", rustgrid_core::PageRequest::new(0, 50))
            .await
            .expect("fetch");
        assert!(
            page.columns
                .iter()
                .any(|column| column.name == "ID" && column.primary_key)
        );
        // A virtual column only exists in `ALL_TAB_COLS` on 19c; reading it from
        // `ALL_TAB_COLUMNS` made every table fail with ORA-00904 (issue #38).
        assert!(
            page.columns
                .iter()
                .any(|column| column.name == "NAME_LEN" && column.generated),
            "the virtual column did not round trip: {:?}",
            page.columns
        );

        connection
            .insert_rows(
                "",
                "APP.RG_T",
                &[RowInsert {
                    values: vec![
                        ("NAME".to_string(), Some("alpha".to_string())),
                        (
                            "CREATED".to_string(),
                            Some("2025-01-02 03:04:05".to_string()),
                        ),
                    ],
                }],
            )
            .await
            .expect("insert");

        connection
            .update_rows(
                "",
                "APP.RG_T",
                &[RowUpdate {
                    set: vec![("NAME".to_string(), Some("beta".to_string()))],
                    keys: vec![("NAME".to_string(), Some("alpha".to_string()))],
                }],
            )
            .await
            .expect("update");

        connection
            .delete_rows(
                "",
                "APP.RG_T",
                &[vec![("NAME".to_string(), Some("beta".to_string()))]],
            )
            .await
            .expect("delete");

        connection.drop_table("", "APP.RG_T").await.expect("drop");
    });
}

/// The table designer's write path: create a table from a `TableSchema`, read it back, alter it and
/// read it again — including a per-column `DESC` in the index.
#[test]
#[ignore = "requires a live Oracle server (RUSTGRID_ORACLE_PASSWORD)"]
fn designer_round_trips_a_table() {
    use rustgrid_core::{ColumnDef, IndexColumnDef, IndexDef, TableSchema};

    let runtime = tokio::runtime::Runtime::new().unwrap();
    runtime.block_on(async {
        let driver = OracleDriver::new();
        let connection = driver.connect(&config()).await.expect("connect");
        let table = "APP.RG_DESIGNER";
        let _ = connection.drop_table("", table).await;

        let mut schema = TableSchema {
            columns: vec![
                ColumnDef {
                    name: "ID".to_string(),
                    data_type: "NUMBER".to_string(),
                    length: "10".to_string(),
                    nullable: false,
                    primary_key: true,
                    auto_increment: true,
                    ..ColumnDef::default()
                },
                ColumnDef {
                    name: "CODE".to_string(),
                    data_type: "VARCHAR2".to_string(),
                    length: "50".to_string(),
                    nullable: true,
                    ..ColumnDef::default()
                },
                ColumnDef {
                    name: "AMOUNT".to_string(),
                    data_type: "NUMBER".to_string(),
                    length: "10".to_string(),
                    decimals: "2".to_string(),
                    nullable: true,
                    comment: "the amount".to_string(),
                    ..ColumnDef::default()
                },
            ],
            ..TableSchema::default()
        };
        schema.indexes.push(IndexDef {
            name: "IX_CODE".to_string(),
            columns: vec![
                IndexColumnDef {
                    name: "CODE".to_string(),
                    descending: true,
                    prefix_length: String::new(),
                },
                IndexColumnDef::new("AMOUNT"),
            ],
            unique: false,
            primary: false,
            index_type: String::new(),
            comment: String::new(),
        });
        connection
            .save_table_schema("", table, None, &schema)
            .await
            .expect("create the table");

        let loaded = connection
            .table_schema("", table)
            .await
            .expect("read the table back");
        assert!(
            loaded
                .columns
                .iter()
                .any(|column| column.name == "ID" && column.primary_key && column.auto_increment),
            "the identity column did not round trip: {:?}",
            loaded.columns
        );
        let index = loaded
            .indexes
            .iter()
            .find(|index| index.name == "IX_CODE")
            .unwrap_or_else(|| panic!("IX_CODE is missing: {:?}", loaded.indexes));
        assert_eq!(index.columns.len(), 2, "{:?}", index.columns);
        assert!(
            index.columns[0].descending,
            "the descending sort did not round trip: {:?}",
            index.columns
        );

        // Alter: a new column, and the index back to an ascending list.
        let mut modified = loaded.clone();
        modified.columns.push(ColumnDef {
            name: "NOTE".to_string(),
            data_type: "VARCHAR2".to_string(),
            length: "50".to_string(),
            nullable: true,
            ..ColumnDef::default()
        });
        let index = modified
            .indexes
            .iter_mut()
            .find(|index| index.name == "IX_CODE")
            .expect("IX_CODE");
        index.columns = vec![IndexColumnDef::new("CODE"), IndexColumnDef::new("AMOUNT")];
        connection
            .save_table_schema("", table, Some(&loaded), &modified)
            .await
            .expect("alter the table");

        let reloaded = connection
            .table_schema("", table)
            .await
            .expect("read the altered table back");
        assert!(reloaded.columns.iter().any(|column| column.name == "NOTE"));
        let index = reloaded
            .indexes
            .iter()
            .find(|index| index.name == "IX_CODE")
            .expect("IX_CODE after the alter");
        assert!(
            !index.columns[0].descending,
            "the ascending sort did not round trip: {:?}",
            index.columns
        );

        connection.drop_table("", table).await.expect("drop");
    });
}

/// The `连接类型 = SID` path: the database field carries a SID and the driver builds a connect
/// descriptor (`(DESCRIPTION=…(CONNECT_DATA=(SID=…)))`), which the live listener must accept.
#[test]
#[ignore = "requires a live Oracle server (RUSTGRID_ORACLE_PASSWORD)"]
fn connects_by_sid_descriptor() {
    let runtime = tokio::runtime::Runtime::new().unwrap();
    runtime.block_on(async {
        let mut config = config();
        // The CDB's SID (the container's `ORACLE_SID`), not the PDB service name.
        config.database = Some(env("RUSTGRID_ORACLE_SID", "FREE"));
        config
            .options
            .insert("oracle.connect_type".to_string(), "sid".to_string());

        let driver = OracleDriver::new();
        let connection = driver
            .connect(&config)
            .await
            .expect("connect via a SID descriptor");

        let version = connection.server_version().await.expect("version");
        assert!(!version.is_empty());

        connection.close().await.expect("close");
    });
}
